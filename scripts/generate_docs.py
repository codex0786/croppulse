"""Regenerate docs/DATA_DICTIONARY.md from the ORM schema and the feature registry."""

from croppulse import models  # noqa: F401
from croppulse.config import REPO_ROOT
from croppulse.db import Base
from croppulse.science.features import FEATURES

out = ["# Data dictionary", "", "Generated by `scripts/generate_docs.py` from `croppulse/models.py` and `croppulse/science/features.py`. Do not edit by hand.", ""]
out += ["## Features", "", "| Feature | Definition | Units | Source | Transformation | Available | Missing data | Intended use | Leakage risk |", "|---|---|---|---|---|---|---|---|---|"]
for f in FEATURES:
    out.append("| " + " | ".join(str(v).replace("|", "/") for v in f.to_dict().values()) + " |")
out += ["", "## Database tables", ""]
for t in Base.metadata.sorted_tables:
    doc = (t.metadata.tables[t.name].info or {}).get("doc", "")
    out += [f"### `{t.name}`", doc, "", "| Column | Type | Nullable | Key |", "|---|---|---|---|"]
    for c in t.columns:
        key = "PK" if c.primary_key else ("FK → " + ", ".join(fk.target_fullname for fk in c.foreign_keys) if c.foreign_keys else "")
        out.append(f"| `{c.name}` | {c.type} | {'yes' if c.nullable else 'no'} | {key} |")
    out.append("")
(REPO_ROOT / "docs" / "DATA_DICTIONARY.md").write_text("\n".join(out))
print("docs/DATA_DICTIONARY.md written")
